export async function getLocale(): Promise<Locale> {
  const c = await (cookies as unknown as () => Promise<any>)();
  const value = c?.get?.("lang")?.value as Locale | undefined;
  return (value && (["en", "zh-HK", "zh-CN"] as const).includes(value)) ? value : "en";
}

export function t(key: string, locale?: Locale): string {
  const l = (locale && (["en", "zh-HK", "zh-CN"] as const).includes(locale) ? locale : "en") as Locale;
  return dictionaries[l][key] ?? dictionaries.en[key] ?? key;
}
