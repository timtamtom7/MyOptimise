import { defineField, defineType } from "sanity";
import { ClipboardList } from "lucide-react";

export default defineType({
  name: "workItem",
  type: "document",
  title: "Work Item",
  icon: ClipboardList,
  groups: [
    { name: "content", title: "Content" },
    { name: "assignment", title: "Assignment" },
    { name: "links", title: "Links" },
    { name: "collaboration", title: "Collaboration" },
    { name: "status", title: "Status" },
  ],
  fields: [
    defineField({
      name: "title",
      type: "string",
      title: "Title",
      group: "content",
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "description",
      type: "text",
      title: "Description",
      group: "content",
    }),
    defineField({
      name: "visibility",
      title: "Visibility",
      type: "string",
      group: "content",
      options: {
        list: [
          { title: "Internal", value: "internal" },
          { title: "Client Visible", value: "client" },
        ],
        layout: "radio",
      },
      initialValue: "internal",
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "isTemplate",
      title: "Is Template",
      type: "boolean",
      group: "content",
      initialValue: false,
    }),
    defineField({
      name: "attachments",
      title: "Attachments",
      type: "array",
      group: "collaboration",
      of: [{ type: "file" }],
    }),
    defineField({
      name: "assignedTo",
      type: "reference",
      title: "Assigned To",
      to: [{ type: "account" }],
      group: "assignment",
    }),
    defineField({
      name: "createdBy",
      type: "reference",
      title: "Created By",
      to: [{ type: "account" }],
      group: "assignment",
      readOnly: true,
    }),
    defineField({
      name: "dueDate",
      type: "datetime",
      title: "Due Date",
      group: "assignment",
    }),
    defineField({
      name: "clientAccount",
      title: "Client Account",
      type: "reference",
      to: [{ type: "account" }],
      options: {
        filter: 'role == "client"',
      },
      group: "links",
    }),
    defineField({
      name: "relatedSignup",
      title: "Related Signup",
      type: "reference",
      to: [{ type: "signup" }],
      group: "links",
    }),
    defineField({
      name: "relatedSponsorship",
      title: "Related Sponsorship",
      type: "reference",
      to: [{ type: "sponsorship" }],
      group: "links",
    }),
    defineField({
      name: "blockedReason",
      title: "Blocked Reason",
      type: "text",
      group: "collaboration",
    }),
    defineField({
      name: "reassignmentRequestedAt",
      title: "Reassignment Requested At",
      type: "datetime",
      group: "collaboration",
      readOnly: true,
    }),
    defineField({
      name: "reassignmentNote",
      title: "Reassignment Note",
      type: "text",
      group: "collaboration",
    }),
    defineField({
      name: "comments",
      title: "Comments",
      type: "array",
      group: "collaboration",
      of: [
        {
          type: "object",
          name: "workItemComment",
          fields: [
            defineField({
              name: "author",
              title: "Author",
              type: "reference",
              to: [{ type: "account" }],
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: "message",
              title: "Message",
              type: "text",
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: "createdAt",
              title: "Created At",
              type: "datetime",
              initialValue: () => new Date().toISOString(),
              readOnly: true,
              validation: (Rule) => Rule.required(),
            }),
          ],
        },
      ],
    }),
    defineField({
      name: "priority",
      title: "Priority",
      type: "string",
      group: "status",
      options: {
        list: [
          { title: "Low", value: "low" },
          { title: "Medium", value: "medium" },
          { title: "High", value: "high" },
        ],
        layout: "radio",
      },
      initialValue: "medium",
    }),
    defineField({
      name: "status",
      title: "Status",
      type: "string",
      group: "status",
      options: {
        list: [
          { title: "To Do", value: "todo" },
          { title: "In Progress", value: "in_progress" },
          { title: "Blocked", value: "blocked" },
          { title: "Done", value: "done" },
        ],
        layout: "radio",
      },
      initialValue: "todo",
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "createdAt",
      title: "Created At",
      type: "datetime",
      initialValue: () => new Date().toISOString(),
      readOnly: true,
      group: "status",
    }),
  ],
});
